# Короткие фамилии без типичного окончания (корейские фамилии в РК и т.п.)
_SHORT_SURNAMES = """
Ким Пак Цой Ли Тен Шин Югай Нам Хан Kim Pak Tsoy Tsoi Li Ten Shin Nam
"""

_TRANSLIT = {
    "а": ["a"], "б": ["b"], "в": ["v"], "г": ["g"], "д": ["d"], "е": ["e"],
    "ё": ["yo", "e"], "ж": ["zh", "j"], "з": ["z"], "и": ["i"], "й": ["i", "y"],
    "к": ["k"], "л": ["l"], "м": ["m"], "н": ["n"], "о": ["o"], "п": ["p"],
    "р": ["r"], "с": ["s"], "т": ["t"], "у": ["u"], "ф": ["f"], "х": ["kh", "h"],
    "ц": ["ts"], "ч": ["ch"], "ш": ["sh"], "щ": ["shch"], "ъ": [""], "ы": ["y", "i"],
    "ь": [""], "э": ["e"], "ю": ["yu"], "я": ["ya"], "ә": ["a", "ä"], "ғ": ["g", "gh"],
    "қ": ["k", "q"], "ң": ["n", "ng"], "ө": ["o", "ö"], "ұ": ["u"], "ү": ["u", "ü"],
    "һ": ["h"], "і": ["i"],
}


def _translit_variants(name: str, limit: int = 16) -> set[str]:
    """Латинские варианты имени: Ержан -> erzhan, yerzhan, erjan, ..."""
    variants = [""]
    for ch in name.lower():
        options = _TRANSLIT.get(ch, [ch])
        variants = [v + o for v in variants for o in options][:limit]
    out = set(variants)
    # «Е» в начале имени по-английски часто пишут как Ye: Yerlan, Yelena
    if name.lower().startswith("е"):
        out |= {"y" + v for v in variants}
    return out


def _build() -> frozenset[str]:
    names: set[str] = set()
    for block in (_KZ_MALE, _KZ_FEMALE, _RU_MALE, _RU_FEMALE):
        for name in block.split():
            names.add(name.lower())
            names |= _translit_variants(name)
    return frozenset(names)


FIRST_NAMES = _build()
SHORT_SURNAMES = frozenset(s.lower() for s in _SHORT_SURNAMES.split())

# Падежные окончания, которые снимаются при поиске имени в словаре:
# «Сергея» -> «Серге» + «й», «Айгуль» без изменений, «Марии» -> «Мари» + «я».
_CASE_STRIP = ("ами", "ями", "ой", "ей", "ом", "ем", "ою", "ею", "а", "я", "у", "ю", "е", "ы", "и")
_NOMINATIVE_ENDINGS = ("", "й", "а", "я", "ь")


def is_first_name(word: str) -> bool:
    w = word.lower()
    if w in FIRST_NAMES:
        return True
    for suffix in _CASE_STRIP:
        if len(w) - len(suffix) >= 2 and w.endswith(suffix):
            stem = w[: -len(suffix)]
            if any(stem + end in FIRST_NAMES for end in _NOMINATIVE_ENDINGS):
                return True
    return False


# Окончания фамилий с падежными формами: Ахметов/Ахметова/Ахметовой/Ахметову,
# Достоевский/-ая/-ого, Шевченко, Ковальчук, Жумабай/Жумабек, Нурсултанулы.
_SURNAME_CYR = re.compile(
    r"(?:"
    r"(?:ов|ев|ёв|ин|ын)(?:а|у|ым|ой|ого|ому|ую|е|ых|ыми)?"
    r"|(?:ск|цк)(?:ий|ая|ого|ой|ому|ую|им|их|ие)"
    r"|енко|ук|юк|бай|бек|беков|бекова"
    r"|улы|ұлы|кызы|қызы|тегі|теги"
    r")$"
)
_SURNAME_LAT = re.compile(
    r"(?:"
    r"(?:ov|ev|yov|in|yn)a?"
    r"|(?:sky|skiy|skii|skaya|tsky|tskaya)"
    r"|enko|uk|yuk|bay|bai|bek|bekov|bekova"
    r"|uly|uli|ulı|kyzy|kizi|qyzy|qızı"
    r")$"
)


def looks_like_surname(word: str) -> bool:
    w = word.lower()
    if w in SHORT_SURNAMES:
        return True
    if len(w) < 4:
        return False
    return bool(_SURNAME_CYR.search(w) or _SURNAME_LAT.search(w))
